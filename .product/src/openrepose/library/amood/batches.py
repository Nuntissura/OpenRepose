class AmoodBatchError(ValueError):
    """Raised when batch input is malformed or a referenced row is missing."""


@dataclass
class LibraryBatch:
    id: UUID
    project_id: UUID
    task_id: UUID
    slug: str
    name: str | None
    tier: str
    primary_explicit_family: str | None
    dedupe_threshold: int
    package_path: str | None
    created_at: datetime | None

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": str(self.id),
            "project_id": str(self.project_id),
            "task_id": str(self.task_id),
            "slug": self.slug,
            "name": self.name,
            "tier": self.tier,
            "primary_explicit_family": self.primary_explicit_family,
            "dedupe_threshold": self.dedupe_threshold,
            "package_path": self.package_path,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }


def create_batch(
    conn: psycopg.Connection[object],
    *,
    project_id: UUID | str,
    task_id: UUID | str,
    slug: str,
    name: str | None = None,
    tier: str = "production",
    primary_explicit_family: str | None = None,
    dedupe_threshold: int = 6,
    package_path: str | None = None,
) -> LibraryBatch:
    if not slug:
        raise AmoodBatchError("batch slug must be non-empty")
    if tier not in _VALID_TIERS:
        raise AmoodBatchError(f"tier must be one of {_VALID_TIERS}; got {tier!r}")
    if not _DEDUPE_THRESHOLD_RANGE[0] <= int(dedupe_threshold) <= _DEDUPE_THRESHOLD_RANGE[1]:
        raise AmoodBatchError(
            f"dedupe_threshold must be in range {_DEDUPE_THRESHOLD_RANGE}; got {dedupe_threshold}"
        )
    with conn.cursor() as cur:
        cur.execute(
            """
            INSERT INTO library_batches
                (project_id, task_id, slug, name, tier, primary_explicit_family,
                 dedupe_threshold, package_path)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
            RETURNING id, project_id, task_id, slug, name, tier,
                      primary_explicit_family, dedupe_threshold, package_path,
                      created_at
            """,
            (
                str(project_id),
                str(task_id),
                slug,
                name,
                tier,
                primary_explicit_family,
                int(dedupe_threshold),
                package_path,
            ),
        )
        row = cur.fetchone()
    conn.commit()
    return _row_to_batch(row)


def get_batch(
    conn: psycopg.Connection[object],
    *,
    batch_id: UUID | str | None = None,
    project_id: UUID | str | None = None,
    slug: str | None = None,
) -> LibraryBatch | None:
    if batch_id is not None:
        where, args = "id = %s", (str(batch_id),)
    elif project_id is not None and slug is not None:
        where, args = "project_id = %s AND slug = %s", (str(project_id), slug)
    else:
        raise AmoodBatchError(
            "get_batch requires batch_id or (project_id, slug)"
        )
    with conn.cursor() as cur:
        cur.execute(
            f"""
            SELECT id, project_id, task_id, slug, name, tier,
                   primary_explicit_family, dedupe_threshold, package_path,
                   created_at
            FROM library_batches WHERE {where}
            """,
            args,
        )
        row = cur.fetchone()
    return _row_to_batch(row) if row else None


def list_batches(
    conn: psycopg.Connection[object],
    *,
    project_id: UUID | str | None = None,
    task_id: UUID | str | None = None,
) -> list[LibraryBatch]:
    where_parts: list[str] = []
    args: list[Any] = []
    if project_id is not None:
        where_parts.append("project_id = %s")
        args.append(str(project_id))
    if task_id is not None:
        where_parts.append("task_id = %s")
        args.append(str(task_id))
    where = ("WHERE " + " AND ".join(where_parts)) if where_parts else ""
    with conn.cursor() as cur:
        cur.execute(
            f"""
            SELECT id, project_id, task_id, slug, name, tier,
                   primary_explicit_family, dedupe_threshold, package_path,
                   created_at
            FROM library_batches {where}
            ORDER BY created_at DESC
            """,
            tuple(args),
        )
        rows = cur.fetchall()
    return [_row_to_batch(r) for r in rows]


def init_batch_package(
    conn: psycopg.Connection[object],
    *,
    project_slug: str,
    batch_slug: str,
    task_id: UUID | str,
    library_root: Path | str,
    tier: str = "production",
    primary_explicit_family: str | None = None,
    dedupe_threshold: int = 6,
) -> dict[str, Any]:
    """Create a batch row + folder layout under
    `<library_root>/<project_slug>/<batch_slug>/`.

    Idempotent: if a batch with this (project_slug, batch_slug) already
    exists, returns the existing batch with `created: False` and a diff
    of any folder-tree drift; otherwise creates the row + folder tree
    inside one transaction and returns `created: True`.

    Folder creation happens inside the DB transaction so a file-system
    failure rolls back the row insert.
    """
    if not project_slug or not batch_slug:
        raise AmoodBatchError("project_slug and batch_slug must be non-empty")

    project = _resolve_project_id(conn, project_slug)
    if project is None:
        raise AmoodBatchError(f"project_slug {project_slug!r} not found")

    existing = get_batch(conn, project_id=project, slug=batch_slug)
    package_dir = Path(library_root) / project_slug / batch_slug

    if existing is not None:
        diffs = _verify_layout(package_dir)
        return {
            "created": False,
            "batch": existing.to_dict(),
            "package_path": str(package_dir),
            "intake_dir": _intake_dir_for_task(conn, task_id),
            "layout_diffs": diffs,
        }

    # Create row + folder layout in one logical transaction. psycopg
    # autocommit is False inside `with conn`; both the SQL INSERT and
    # the file-system mkdir live inside the same `with conn:` block
    # (caller's). On any exception we rollback explicitly so the
    # advisory layer is clean.
    try:
        batch = create_batch(
            conn,
            project_id=project,
            task_id=task_id,
            slug=batch_slug,
            tier=tier,
            primary_explicit_family=primary_explicit_family,
            dedupe_threshold=dedupe_threshold,
            package_path=str(package_dir),
        )
        _materialize_layout(
            package_dir=package_dir,
            project_slug=project_slug,
            batch=batch,
        )
    except Exception:
        conn.rollback()
        raise

    return {
        "created": True,
        "batch": batch.to_dict(),
        "package_path": str(package_dir),
        "intake_dir": _intake_dir_for_task(conn, task_id),
        "layout_diffs": [],
    }


def _materialize_layout(
    *,
    package_dir: Path,
    project_slug: str,
    batch: LibraryBatch,
) -> None:
    package_dir.mkdir(parents=True, exist_ok=True)
    for sub in _PACKAGE_SUBDIRS:
        (package_dir / sub).mkdir(parents=True, exist_ok=True)
    index_path = package_dir / "INDEX.md"
    readme_path = package_dir / "README.md"
    if not index_path.exists():
        index_path.write_text(
            _INDEX_TEMPLATE.format(
                project_slug=project_slug,
                batch_slug=batch.slug,
                tier=batch.tier,
                primary_explicit_family=batch.primary_explicit_family or "",
                dedupe_threshold=batch.dedupe_threshold,
                package_path=str(package_dir),
                created_at=(batch.created_at.isoformat() if batch.created_at else ""),
            ),
            encoding="utf-8",
        )
    if not readme_path.exists():
        readme_path.write_text(
            _README_TEMPLATE.format(
                batch_slug=batch.slug,
                batch_id=str(batch.id),
            ),
            encoding="utf-8",
        )


def _verify_layout(package_dir: Path) -> list[str]:
    """Return human-readable diffs for missing required subdirs/files.

    Empty list = layout matches the canonical package shape. Missing
    items are reported but not auto-created on idempotent re-run; the
    operator decides whether to delete + re-init.
    """
    diffs: list[str] = []
    if not package_dir.exists():
        diffs.append(f"missing: {package_dir}")
        return diffs
    for sub in _PACKAGE_SUBDIRS:
        if not (package_dir / sub).exists():
            diffs.append(f"missing subdir: {sub}")
    for top in ("INDEX.md", "README.md"):
        if not (package_dir / top).exists():
            diffs.append(f"missing top file: {top}")
    return diffs


def _resolve_project_id(
    conn: psycopg.Connection[object],
    project_slug: str,
) -> UUID | None:
    with conn.cursor() as cur:
        cur.execute(
            "SELECT id FROM library_projects WHERE slug = %s",
            (project_slug,),
        )
        row = cur.fetchone()
    return row[0] if row else None


def _intake_dir_for_task(
    conn: psycopg.Connection[object],
    task_id: UUID | str,
) -> str | None:
    with conn.cursor() as cur:
        cur.execute("SELECT intake_dir FROM library_tasks WHERE id = %s", (str(task_id),))
        row = cur.fetchone()
    return row[0] if row else None


def _row_to_batch(row: Any) -> LibraryBatch:
    return LibraryBatch(
        id=row[0],
        project_id=row[1],
        task_id=row[2],
        slug=row[3],
        name=row[4],
        tier=row[5],
        primary_explicit_family=row[6],
        dedupe_threshold=int(row[7]),
        package_path=row[8],
        created_at=row[9],
    )
